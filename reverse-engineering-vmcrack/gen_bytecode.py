#!/usr/bin/env python3
"""
Author-side "compiler": assembles the check program with vm_common,
computes the target bytes for the real flag, then obfuscates both the
bytecode and the target before emitting bytecode.h for vm.c to #include.

Two obfuscation layers get applied here (a third, the anti-debug key
corruption, lives in vm.c itself since it depends on a runtime check):

  1. The bytecode is XOR'd against a repeating 4-byte key (EK) before
     being embedded, so a raw hexdump of the binary's .rodata doesn't
     show the opcodes directly -- they have to be decoded first.
  2. The 20-byte target is XOR'd against a single mask byte for the
     same reason.

Run this to regenerate bytecode.h (e.g. to mint a new flag):
    python3 gen_bytecode.py
"""
import vm_common as vm

CONTENT_LEN = 20
FLAG_CONTENT = "s3lf_d3c0d1ng_vm9000"
assert len(FLAG_CONTENT) == CONTENT_LEN

KEY = [0x5A, 0x17, 0xC3, 0x4E, 0x91, 0x2D, 0x88, 0x6F]
CONSTS = [0x11, 0x7F, 0x33, 0xA6]
IV = 0xC9

ENCODE_KEY = [0xDE, 0xAD, 0xBE, 0xEF]     # bytecode-at-rest XOR key
TARGET_MASK = 0x5A                        # target-at-rest XOR mask


def main():
    program = vm.build_program(KEY, CONSTS, CONTENT_LEN)
    target = vm.run_vm(program, [ord(c) for c in FLAG_CONTENT], IV, CONTENT_LEN)

    encoded_bytecode = [b ^ ENCODE_KEY[i % 4] for i, b in enumerate(program)]
    encoded_target = [b ^ TARGET_MASK for b in target]

    def c_array(name, values, width=12):
        lines = []
        for i in range(0, len(values), width):
            chunk = values[i:i + width]
            lines.append("    " + ", ".join(f"0x{v:02x}" for v in chunk) + ",")
        body = "\n".join(lines)
        return f"static const unsigned char {name}[] = {{\n{body}\n}};"

    with open("bytecode.h", "w") as f:
        f.write("// Auto-generated by gen_bytecode.py -- do not hand-edit.\n")
        f.write(f"#define CONTENT_LEN {CONTENT_LEN}\n")
        f.write(f"#define IV 0x{IV:02x}\n")
        f.write(f"#define TARGET_MASK 0x{TARGET_MASK:02x}\n\n")
        f.write(c_array("ENCODE_KEY", ENCODE_KEY) + "\n\n")
        f.write(c_array("ENCODED_BYTECODE", encoded_bytecode) + "\n")
        f.write(f"#define BYTECODE_LEN {len(encoded_bytecode)}\n\n")
        f.write(c_array("ENCODED_TARGET", encoded_target) + "\n")

    print(f"wrote bytecode.h -- program is {len(program)} bytes, "
          f"flag{{'{FLAG_CONTENT}'}}")


if __name__ == "__main__":
    main()
